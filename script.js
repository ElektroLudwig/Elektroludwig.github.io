/* ==================================================
   OTVORENIE FOTKY Z GALÉRIE
================================================== */

function openLightboxFromGallery(projectIndex, clickedPhoto) {
  const gallery = document.getElementById(
    "project-gallery-" + projectIndex
  );

  if (!gallery) {
    return;
  }

  const loadedImages = gallery.querySelectorAll(
    ".project-gallery-item img"
  );

  currentGalleryPhotos = [];

  loadedImages.forEach(function(image) {
    if (image.complete && image.naturalWidth > 0) {
      currentGalleryPhotos.push(image.src);
    }
  });

  if (currentGalleryPhotos.length === 0) {
    return;
  }

  const absoluteClickedPhoto = new URL(
    clickedPhoto,
    window.location.href
  ).href;

  currentPhotoIndex = currentGalleryPhotos.indexOf(absoluteClickedPhoto);

  if (currentPhotoIndex < 0) {
    currentPhotoIndex = 0;
  }

  currentLightboxProjectIndex = Number(projectIndex);

  createLightbox();
  updateLightbox();

  lightbox.classList.add("open");
  document.body.style.overflow = "hidden";
}


/* ==================================================
   AKTUALIZÁCIA LIGHTBOXU
================================================== */

function updateLightbox() {
  if (!lightbox || currentGalleryPhotos.length === 0) {
    return;
  }

  lightboxImage.src = currentGalleryPhotos[currentPhotoIndex];

  const galleryImage = Array.from(
    document.querySelectorAll(
      "#project-gallery-" + currentLightboxProjectIndex + " img"
    )
  ).find(image => image.src === currentGalleryPhotos[currentPhotoIndex]);

  lightboxImage.alt =
    galleryImage?.alt ||
    t("photo") + " " + (currentPhotoIndex + 1);

  lightboxCounter.textContent =
    (currentPhotoIndex + 1) + " / " + currentGalleryPhotos.length;

  const previousButton = lightbox.querySelector(".lightbox-prev");
  const nextButton = lightbox.querySelector(".lightbox-next");

  if (currentGalleryPhotos.length <= 1) {
    previousButton.style.display = "none";
    nextButton.style.display = "none";
  } else {
    previousButton.style.display = "flex";
    nextButton.style.display = "flex";
  }
}


/* ==================================================
   PREDCHÁDZAJÚCA A NASLEDUJÚCA FOTKA
================================================== */

function showPreviousPhoto() {
  if (currentGalleryPhotos.length === 0) {
    return;
  }

  currentPhotoIndex--;

  if (currentPhotoIndex < 0) {
    currentPhotoIndex = currentGalleryPhotos.length - 1;
  }

  updateLightbox();
}

function showNextPhoto() {
  if (currentGalleryPhotos.length === 0) {
    return;
  }

  currentPhotoIndex++;

  if (currentPhotoIndex >= currentGalleryPhotos.length) {
    currentPhotoIndex = 0;
  }

  updateLightbox();
}


/* ==================================================
   ZATVORENIE LIGHTBOXU
================================================== */

function closeLightbox() {
  if (!lightbox) {
    return;
  }

  lightbox.classList.remove("open");
  document.body.style.overflow = "";
}


