function setLanguage(language) {
  if (!Object.prototype.hasOwnProperty.call(supportedLanguages, language)) {
    return;
  }

  currentLanguage = language;

  try {
    localStorage.setItem(languageStorageKey, language);
  } catch (_) {
    // Bez úložiska sa jazyk zmení pre aktuálne otvorenú stránku.
  }

  applyStaticTranslations();
  refreshProjectsLanguage();

  if (formMessage?.classList.contains("visible")) {
    formMessage.textContent = t("formPending");
  }

  document
    .querySelectorAll(
      "#inquiryForm input, #inquiryForm select, #inquiryForm textarea"
    )
    .forEach(element => {
      element.setCustomValidity("");

      if (element.dataset.validationShown) {
        localizeValidation(element);
      }
    });
}

function localizeValidation(element) {
  element.setCustomValidity("");

  if (element.validity.valueMissing) {
    element.setCustomValidity(
      t(element.type === "checkbox" ? "consentRequired" : "requiredField")
    );
  } else if (
    element.validity.typeMismatch &&
    element.type === "email"
  ) {
    element.setCustomValidity(t("invalidEmail"));
  }
}


