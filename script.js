function initializeLanguageSwitcher() {
  const switcher = document.querySelector(".language-switcher");
  const toggle = switcher.querySelector(".language-current");
  const menu = switcher.querySelector(".language-menu");

  menu.innerHTML = Object.entries(supportedLanguages)
    .map(([code, name]) => `
      <a href="#" data-language="${code}" lang="${code}">
        <i class="fas fa-language" aria-hidden="true"></i>
        ${name}
      </a>
    `)
    .join("");

  function closeMenu() {
    switcher.classList.remove("is-open");
    toggle.setAttribute("aria-expanded", "false");
  }

  toggle.addEventListener("click", () => {
    const open = switcher.classList.toggle("is-open");
    toggle.setAttribute("aria-expanded", String(open));
  });

  toggle.addEventListener("keydown", event => {
    if (event.key === "ArrowDown") {
      event.preventDefault();
      switcher.classList.add("is-open");
      toggle.setAttribute("aria-expanded", "true");
      menu.querySelector("a").focus();
    }
  });

  menu.addEventListener("click", event => {
    const link = event.target.closest("[data-language]");

    if (!link) {
      return;
    }

    event.preventDefault();
    setLanguage(link.dataset.language);
    closeMenu();
    toggle.focus();
  });

  document.addEventListener("click", event => {
    if (!switcher.contains(event.target)) {
      closeMenu();
    }
  });

  switcher.addEventListener("focusout", event => {
    if (!switcher.contains(event.relatedTarget)) {
      closeMenu();
    }
  });

  document.addEventListener("keydown", event => {
    if (
      event.key === "Escape" &&
      switcher.classList.contains("is-open")
    ) {
      closeMenu();
      toggle.focus();
    }
  });

  document
    .querySelectorAll(
      "#inquiryForm input, #inquiryForm select, #inquiryForm textarea"
    )
    .forEach(element => {
      element.addEventListener("invalid", () => {
        element.dataset.validationShown = "true";
        localizeValidation(element);
      });

      element.addEventListener("input", () => {
        element.setCustomValidity("");
        delete element.dataset.validationShown;
      });

      element.addEventListener("change", () => {
        element.setCustomValidity("");
        delete element.dataset.validationShown;
      });
    });

  applyStaticTranslations();
}


