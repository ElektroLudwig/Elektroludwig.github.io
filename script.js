function activateProjectButtons() {
  const openButtons = document.querySelectorAll("[data-project-open]");
  const closeButtons = document.querySelectorAll("[data-project-close]");

  openButtons.forEach(function(button) {
    button.addEventListener("click", function() {
      const projectIndex = button.dataset.projectOpen;

      const detail = document.getElementById(
        "project-detail-" + projectIndex
      );

      if (!detail) {
        return;
      }

      document.querySelectorAll(".project-detail.open").forEach(
        function(openDetail) {
          if (openDetail !== detail) {
            openDetail.classList.remove("open");
          }
        }
      );

      detail.classList.add("open");

      setTimeout(function() {
        detail.scrollIntoView({
          behavior: "smooth",
          block: "start"
        });
      }, 50);
    });
  });

  closeButtons.forEach(function(button) {
    button.addEventListener("click", function() {
      const projectIndex = button.dataset.projectClose;

      const detail = document.getElementById(
        "project-detail-" + projectIndex
      );

      if (!detail) {
        return;
      }

      detail.classList.remove("open");

      const openButton = document.querySelector(
        `[data-project-open="${projectIndex}"]`
      );

      if (openButton) {
        setTimeout(function() {
          openButton.scrollIntoView({
            behavior: "smooth",
            block: "center"
          });
        }, 50);
      }
    });
  });
}


