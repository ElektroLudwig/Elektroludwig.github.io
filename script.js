/* ==================================================
   AUTOMATICKÁ GALÉRIA

   Skúša fotografie 01.jpeg až 50.jpeg.
   Existujúce zobrazí, neexistujúce odstráni.
================================================== */

function createAutomaticGallery(project, projectIndex) {
  const gallery = document.getElementById(
    "project-gallery-" + projectIndex
  );

  const galleryArea = document.getElementById(
    "project-gallery-area-" + projectIndex
  );

  if (!gallery || !galleryArea) {
    return;
  }

  const projectFolder = project.priecinok || "";
  const basePath = "images/projekty/" + projectFolder + "/";

  galleryArea.style.display = "none";

  let foundPhotos = 0;

  for (let photoNumber = 1; photoNumber <= 50; photoNumber++) {
    const formattedNumber = String(photoNumber).padStart(2, "0");
    const photoPath = basePath + formattedNumber + ".jpeg";

    const galleryItem = document.createElement("div");

    galleryItem.className = "project-gallery-item";
    galleryItem.setAttribute("role", "button");
    galleryItem.setAttribute("tabindex", "0");
    galleryItem.setAttribute("data-photo-path", photoPath);

    const image = document.createElement("img");

    image.alt =
      (project.nazov || t("project")) +
      " – " +
      t("photo") +
      " " +
      photoNumber;

    // Udalosti nastavíme pred src, aby fungovali aj fotky z cache.
    image.onload = function() {
      foundPhotos++;
      galleryArea.style.display = "";
    };

    image.onerror = function() {
      galleryItem.remove();
    };

    galleryItem.addEventListener("click", function() {
      openLightboxFromGallery(projectIndex, photoPath);
    });

    galleryItem.addEventListener("keydown", function(event) {
      if (event.key === "Enter" || event.key === " ") {
        event.preventDefault();
        openLightboxFromGallery(projectIndex, photoPath);
      }
    });

    galleryItem.appendChild(image);
    gallery.appendChild(galleryItem);

    image.src = photoPath;
  }
}


